#!/usr/bin/env node
/**
 * Compiles contracts/StockMaxxIndexRegistry.sol with `solc` and writes
 * the ABI + bytecode to src/lib/contracts/ (TS module + JSON artifact).
 *
 * Usage: npm run compile:contracts
 */
import fs from "node:fs";
import path from "node:path";
import solc from "solc";

const ROOT = process.cwd();
const outDir = path.join(ROOT, "src", "lib", "contracts");

export function compile(sources, { viaIR = true } = {}) {
  const input = {
    language: "Solidity",
    sources: Object.fromEntries(
      Object.entries(sources).map(([name, file]) => [name, { content: fs.readFileSync(path.join(ROOT, file), "utf8") }])
    ),
    settings: {
      viaIR,
      optimizer: { enabled: true, runs: 200 },
      evmVersion: "cancun",
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
    },
  };
  const findImports = (p) => {
    const candidate = path.join(ROOT, p);
    return fs.existsSync(candidate) ? { contents: fs.readFileSync(candidate, "utf8") } : { error: `File not found: ${p}` };
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
  let fatal = false;
  for (const err of output.errors || []) {
    console.log(`[${err.severity.toUpperCase()}] ${err.formattedMessage.trim()}`);
    if (err.severity === "error") fatal = true;
  }
  if (fatal) process.exit(1);
  return output;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));

if (isMain) {
  console.log("Compiling StockMaxxIndexRegistry.sol with solc:", solc.version());
  const output = compile({ "contracts/StockMaxxIndexRegistry.sol": "contracts/StockMaxxIndexRegistry.sol" });
  const c = output.contracts["contracts/StockMaxxIndexRegistry.sol"]["StockMaxxIndexRegistry"];
  const abi = c.abi;
  const bytecode = `0x${c.evm.bytecode.object}`;
  const deployedBytecode = `0x${c.evm.deployedBytecode.object}`;

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, "StockMaxxIndexRegistryArtifact.json"),
    JSON.stringify(
      { contractName: "StockMaxxIndexRegistry", compilerVersion: solc.version(), abi, bytecode, deployedBytecode },
      null,
      2
    )
  );
  fs.writeFileSync(
    path.join(outDir, "StockMaxxIndexRegistryABI.ts"),
    `// AUTO-GENERATED BY scripts/compile-contracts.mjs — DO NOT EDIT MANUALLY
export const INDEX_REGISTRY_COMPILER = ${JSON.stringify(solc.version())};
export const INDEX_REGISTRY_BYTECODE = ${JSON.stringify(bytecode)} as \`0x\${string}\`;
export const INDEX_REGISTRY_ABI = ${JSON.stringify(abi, null, 2)} as const;
`
  );

  console.log("✅ Compilation succeeded");
  console.log(`   ABI entries      : ${abi.length}`);
  console.log(`   Runtime size     : ${(deployedBytecode.length - 2) / 2} bytes`);
  console.log("   Written to       : src/lib/contracts/StockMaxxIndexRegistryABI.ts (+ Artifact.json)");
}
